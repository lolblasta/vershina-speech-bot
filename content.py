TRACKS = {
    "launch": TRACK_LAUNCH,
    "sound_r": TRACK_SOUND_R,
    "general": TRACK_GENERAL,
}

AGE_GROUPS = {
    "young": "1.5–3 года",
    "middle": "3–5 лет",
    "older": "5–7 лет",
}

PROBLEMS = {
    "launch": "Мало говорит / не говорит",
    "sound_r": "Не произносит звук Р",
    "general": "Хочу развить речь в целом",
}

# Рекомендации трека по возрасту + проблеме
TRACK_MAP = {
    ("young", "launch"):  "launch",
    ("young", "general"): "launch",
    ("young", "sound_r"): "launch",  # в 1.5-3 года Р ещё рано — переводим на запуск
    ("middle", "launch"): "launch",  # 3-5 лет, мало говорит → трек запуска речи
    ("middle", "general"):"general",
    ("middle", "sound_r"):"sound_r",
    ("older", "launch"):  "general",
    ("older", "general"): "general",
    ("older", "sound_r"): "sound_r",
}

def get_track(age_group: str, problem: str) -> str:
    return TRACK_MAP.get((age_group, problem), "general")

def get_exercise(track: str, day: int) -> dict | None:
    exercises = TRACKS.get(track, [])
    for ex in exercises:
        if ex["day"] == day:
            return ex
    return None

def format_exercise(ex: dict, day: int, total: int = 30) -> str:
    return (
        f"{ex['emoji']} *День {day} из {total}*\n"
        f"*{ex['title']}*\n\n"
        f"{ex['body']}"
    )
